import { chromium } from 'playwright';
const BASE = 'http://localhost:5101';
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } });
const page = await context.newPage();
page.on('console', (m) => console.log('CONSOLE', m.type(), m.text()));
page.on('pageerror', (e) => console.log('PAGEERROR', String(e)));
await page.goto(BASE, { waitUntil: 'domcontentloaded' });
await page.waitForSelector('input[type=email]', { timeout: 20000 });
await page.fill('input[type=email]', 'tester@example.com');
await page.fill('input[type=password]', 'password123');
await page.click('button[type=submit]');
await page.waitForSelector('input[type=email]', { state: 'detached', timeout: 20000 });
await page.goto(`${BASE}/tasks`, { waitUntil: 'networkidle' });
await page.waitForSelector('h2:has-text("Kanban Board")', { timeout: 20000 });
console.log('board loaded, reloading...');
await page.reload({ waitUntil: 'domcontentloaded' });
await page.waitForTimeout(5000);
console.log('URL after reload:', page.url());
console.log('BODY:', (await page.evaluate(() => document.body.innerText)).slice(0, 500));
await page.screenshot({ path: '/tmp/reload-debug.png' });
await browser.close();
